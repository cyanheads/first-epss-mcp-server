/** Explain score meaning, model provenance, coverage and transparent triage policy. */
export const epssListReference = tool('epss_list_reference', {
  description:
    'Explain FIRST EPSS interpretation, model publishing dates, lookup coverage and transparent prioritization policy. Use this static reference before interpreting missing scores, score movement or probability versus percentile thresholds.',
  annotations: { readOnlyHint: true, idempotentHint: true, openWorldHint: false },
  input: z.object({
    topic: z
      .enum(['all', ...topics])
      .default('all')
      .describe(
        'interpretation: score meaning; models: publishing history; coverage: limits and missing data; prioritization: tier policy; all: every topic.',
      ),
  }),
  output: z.object({
    topics: z
      .array(
        z
          .object({
            topic: z.enum(topics).describe('Reference topic.'),
            guidance: z.string().describe('Interpretive guidance.'),
            facts: z
              .array(z.string().describe('Documented fact or policy.'))
              .describe('Detailed reference facts.'),
            sources: z
              .array(z.string().describe('Primary-source URL.'))
              .describe('Supporting primary sources.'),
          })
          .describe('Guidance and supporting facts for one topic.'),
      )
      .describe('Selected reference topics.'),
    verifiedAt: z.literal('2026-10-18').describe('Primary-source verification date.'),
  }),
  handler(input) {
    return {
      topics: reference.filter((item) => input.topic === 'all' || item.topic === input.topic),
      verifiedAt: '2026-10-18' as const,
    };
  },
  format(result) {
    return [
      {
        type: 'text',
        text: [
          `Verified at: ${result.verifiedAt}`,
          ...result.topics.map((t) =>
            [
              `## ${t.topic}`,
              t.guidance,
              ...t.facts.map((fact) => `- ${fact}`),
              'Sources:',
              ...t.sources.map((source) => `- ${source}`),
            ].join('\n'),
          ),
        ].join('\n\n'),
      },
    ];
  },
});
